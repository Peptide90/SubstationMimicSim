export type Phase = 'A' | 'B' | 'C' | 'N' | 'E';

export type ViewMode = 'single-line' | 'three-phase';

export interface Point {
  x: number;
  y: number;
}

export interface Terminal {
  id: string;
  name: string;
  offset: Point;
  phaseApplicability: Phase[];
}

export interface ConnectionPoint {
  id: string;
  position: Point;
  snappedTo?: {
    objectId: string;
    terminalId?: string;
    conductorId?: string;
  };
}

export interface LabelMetadata {
  text: string;
  autoGenerated: boolean;
  manualOverride: boolean;
  marker?: string;
}

export interface SimulationMetadata {
  role?: 'source' | 'load' | 'feeder' | 'switching' | 'measurement';
  interlockGroupIds?: string[];
  damaged?: boolean;
  faulted?: boolean;
}

export type PhaseMode = 'single-phase' | 'three-phase';
export type RenderExpansion = 'single-symbol' | 'per-phase-symbols';
export type FlowDirection = 'forward' | 'reverse' | 'bidirectional' | 'unknown';
export type FaultType =
  | 'phase-to-earth'
  | 'phase-to-phase'
  | 'three-phase'
  | 'open-circuit'
  | 'high-impedance'
  | 'transient'
  | 'persistent'
  | 'A-E'
  | 'B-E'
  | 'C-E'
  | 'A-B'
  | 'B-C'
  | 'C-A'
  | 'A-B-C'
  | 'A-B-C-E'
  | 'hot-joint';

export type ThermalState = 'normal' | 'warm' | 'hot' | 'critical';
export type ProtectionElementType = 'overcurrent' | 'earth-fault' | 'thermal-overload' | 'breaker-fail' | 'differential';
